#used to store decimal(floating point) numbers...
x<- 20.5
print(x)
class(x)
print(typeof(x))


#used to store text ,words and a sentences...
x<- "Hello"
print(x)
class(x)
print(typeof(x))


#Used to store TRUE or FALSE values...
x<-TRUE
print(x)
class(x)
print(typeof(x))


#used to store whole number and add "L" after the number to make it an integer...
x<-20L
